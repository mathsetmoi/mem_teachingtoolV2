// T13. Le poste remis à zéro : le soir, le classeur s'enregistre sur la clé ;
// le lendemain, un profil neuf ouvre le fichier de la clé (Ctrl + O, la case
// « Enregistrer automatiquement les changements dans ce fichier » cochée
// d'office) : le classeur revient exactement, avec son identité, et la clé
// reprend sur le même fichier.
import { chromium, V, DEV, ok, info, dort, INIT, ECOUTER_TOASTS, toasts, suivre, pret, ecrire, entree, etat, opfsLire, lireMemc, formesIds, attendreEcrites, etatDeLaPage, memeContenu, erreurs } from './commun.mjs'
const nav = await chromium.launch()
// ---- Le soir ----
const ctxA = await nav.newContext({ viewport: { width: 1366, height: 768 } })
await ctxA.addInitScript(INIT); await ctxA.addInitScript(ECOUTER_TOASTS)
const a = await ctxA.newPage(); suivre(a, 'soir')
await a.goto(DEV); await pret(a); await a.waitForTimeout(500)
for (let i = 0; i < 4; i++) await ecrire(a, 200 + i * 60, 250 + i * 30)
await a.evaluate(() => window.__app.ajouterPage?.())
await a.waitForTimeout(300)
await ecrire(a, 300, 400)
await a.evaluate(() => { window.__nomChoisi = 'cle.memc' })
await entree(a, 'activer-cle')
await attendreEcrites(a, 1, 15000)
await ecrire(a, 500, 300)
await a.waitForTimeout(25000)
const soir = await etatDeLaPage(a)
const idA = await a.evaluate(() => window.__app.classeur.id)
const octetsCle = await opfsLire(a, 'cle.memc')
const luSoir = lireMemc(octetsCle)
ok(memeContenu(luSoir.doc, soir), `le soir : la clé a exactement le classeur (${luSoir.ids.length} traits, ${luSoir.pages} pages)`)
await ctxA.close()
// ---- Le lendemain, profil neuf ----
const ctxB = await nav.newContext({ viewport: { width: 1366, height: 768 } })
await ctxB.addInitScript(INIT); await ctxB.addInitScript(ECOUTER_TOASTS)
const b = await ctxB.newPage(); suivre(b, 'matin')
await b.goto(DEV); await pret(b); await b.waitForTimeout(500)
await b.evaluate(async b64 => {
  const h = await (await navigator.storage.getDirectory()).getFileHandle('cle.memc', { create: true })
  const w = await window.__cwOrig.call(h); await w.write(Uint8Array.from(atob(b64), c => c.charCodeAt(0))); await w.close()
  window.__aOuvrir = 'cle.memc'
}, octetsCle.toString('base64'))
await b.keyboard.press('Control+o')
await b.waitForSelector('dialog[open] [data-a="ajouter"]', { timeout: 15000 })
const d = await b.evaluate(() => { const x = document.querySelector('dialog[open]'); return { boutons: [...x.querySelectorAll('.actions button')].map(b => b.textContent), case: x.querySelector('.case-cle input')?.checked ?? null } })
info('la fenêtre', d)
await b.click('dialog[open] [data-a="ajouter"]')
await b.waitForURL(/classeur=/, { timeout: 15000 }).catch(() => {})
await b.waitForFunction(id => window.__app?.classeur?.id === id, idA, { timeout: 20000 }).catch(() => {})
await pret(b); await b.waitForTimeout(1500)
const matin = await etatDeLaPage(b)
ok(await b.evaluate(() => window.__app.classeur.id) === idA && memeContenu(matin, soir), 'le matin : le classeur revient exactement, avec son id', { id: await b.evaluate(() => window.__app.classeur.id), idA })
let e = await etat(b)
info('l\'état du matin', { court: e.court, cle: e.lignes.find(l => l.startsWith('cle')), toasts: await toasts(b) })
ok(e.cle.etat === 'ok' && e.cle.nom === 'cle.memc', '   … la clé reprend sur le même fichier', e.cle)
await ecrire(b, 600, 450)
await b.waitForTimeout(25000)
const luMatin = lireMemc(await opfsLire(b, 'cle.memc'))
const ids = await formesIds(b)
ok(luMatin.entete.id === idA && memeContenu(luMatin.doc, await etatDeLaPage(b)) && ids.every(i => luMatin.ids.includes(i)), `   … un trait le matin : écrit dans le même fichier, même id (${luMatin.ids.length} traits)`, { entete: luMatin.entete })
e = await etat(b)
info('après', { court: e.court, cle: e.lignes.find(l => l.startsWith('cle')) })
console.log('erreurs JS :', erreurs)
await nav.close()
