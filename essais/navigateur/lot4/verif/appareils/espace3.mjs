// Après × (souris), Espace seul (appuyé, relâché) : rouvre-t-il la bibliothèque ? Et Espace + glisser à la plume.
import { lancer, contexte, ouvrir, info, ok, dort, ecrireTraits } from './outils.mjs'
const nav = await lancer()
const ctx = await contexte(nav)
const p = await ouvrir(ctx, '', 'espace3')
await ecrireTraits(p, 3)
await p.click('.bouton-classeur'); await p.waitForSelector('.bibliotheque:not([hidden])'); await dort(400)
await p.click('.biblio-fermer'); await dort(500)
info('focus après ×', await p.evaluate(() => ({ a: document.activeElement?.className, fv: document.activeElement?.matches(':focus-visible') })))
await p.keyboard.press(' '); await dort(600)
const r = await p.evaluate(() => !document.querySelector('.bibliotheque').hidden)
ok(!r, 'Après × à la souris : Espace seul ne rouvre pas la bibliothèque', { biblio: r })
if (r) { await p.keyboard.press('Escape'); await dort(400) }
// Espace + glisser à la plume (CDP pen)
const cdp = await ctx.newCDPSession(p)
const st = (type, x, y) => cdp.send('Input.dispatchMouseEvent', { type, x, y, pointerType: 'pen', button: type === 'mouseMoved' ? 'none' : 'left', buttons: type === 'mouseReleased' ? 0 : (type === 'mousePressed' ? 1 : 0), clickCount: 1, force: 0.5 })
const cam0 = await p.evaluate(() => [window.__app.cam.x, window.__app.cam.y]), f0 = await p.evaluate(() => window.__app.formes.length)
info('focus avant le geste', await p.evaluate(() => document.activeElement?.className))
await p.keyboard.down(' ')
await st('mouseMoved', 700, 400); await st('mousePressed', 700, 400)
for (let i = 1; i <= 10; i++) await cdp.send('Input.dispatchMouseEvent', { type: 'mouseMoved', x: 700 + i * 15, y: 400 + i * 10, pointerType: 'pen', button: 'none', buttons: 1, force: 0.5 })
await st('mouseReleased', 850, 500); await p.keyboard.up(' '); await dort(600)
const r2 = await p.evaluate(() => ({ cam: [window.__app.cam.x, window.__app.cam.y], formes: window.__app.formes.length, biblio: !document.querySelector('.bibliotheque').hidden }))
ok(r2.formes === f0 && (r2.cam[0] !== cam0[0] || r2.cam[1] !== cam0[1]), 'À la plume : Espace + glisser déplace la vue, n\'écrit rien', { cam0, f0, ...r2 })
await nav.close()
