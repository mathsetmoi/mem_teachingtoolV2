// Point 3 : ordre et groupes, à la souris et au clavier (1366 × 768).
import * as O from './lib/outils.mjs'
const { ok, note, C } = O
const ctx = await O.contexte()
const { p } = await O.ouvrir(ctx, 'souris')
await p.evaluate(O.IMAGES); await p.evaluate(O.PAGE_NEUVE)
const choisir = ids => p.evaluate(ids => { const a = window.__app; a.selection.clear(); for (const i of ids) a.selection.add(i); a.options = null; a.rendu.redessinerDirect(); a.ui.maj() }, ids)
const T1 = await O.poser(p, O.trait(200, 200, 150))
const T2 = await O.poser(p, O.trait(200, 260, 150))
const Tri = await O.poser(p, O.triangle(450, 150))
const groupes = ids => p.evaluate(ids => ids.map(i => window.__app.forme(i)?.groupe ?? null), ids)
// Grouper par le menu commun
await choisir([T1, T2, Tri])
await O.clicDroit(p, 275, 200)
let e = await O.etat(p)
note('menu commun', e)
await p.locator('.panneau-forme button', { hasText: 'Grouper' }).click(); await p.waitForTimeout(200)
const g = await groupes([T1, T2, Tri])
ok(g[0] && g.every(x => x === g[0]), 'Grouper (menu commun) : un groupe', g)
const pileG = await O.pile(p)
e = await O.etat(p)
note('après Grouper (menu)', { e, msgs: await O.msgs(p) })
await p.keyboard.press('Escape'); await O.vider(p)
// Un clic sur un membre prend tout le groupe ; un second ne prend que lui
await O.clic(p, 275, 260)
ok((await O.sel(p)).length === 3, 'Un clic sur un membre prend le groupe', await O.sel(p))
await p.waitForTimeout(400)
await O.clic(p, 275, 260)
await p.waitForTimeout(700)
ok(JSON.stringify(await O.sel(p)) === JSON.stringify([T2]), 'Un second clic simple ne prend que ce membre', { sel: await O.sel(p), msgs: (await O.msgs(p)).slice(-1) })
await O.vider(p); await O.clic(p, 275, 260); await p.waitForTimeout(200)
// Ctrl + D : un groupe neuf, tout le double pris
await p.keyboard.press('Control+d'); await p.waitForTimeout(250)
const doubles = await O.sel(p)
const gd = await groupes(doubles)
ok(doubles.length === 3 && gd[0] && gd.every(x => x === gd[0]) && gd[0] !== g[0], 'Ctrl + D : le double du groupe est un groupe neuf, pris en entier', { doubles, gd })
await p.keyboard.press('Control+z'); await p.waitForTimeout(150)
// Copier / coller
await O.vider(p); await O.clic(p, 275, 260); await p.waitForTimeout(150)
await p.keyboard.press('Control+c'); await p.waitForTimeout(150)
await p.mouse.move(900, 500)
await p.keyboard.press('Control+v'); await p.waitForTimeout(300)
const colles = await O.sel(p), gc = await groupes(colles)
ok(colles.length === 3 && gc[0] && gc.every(x => x === gc[0]) && gc[0] !== g[0], 'Copier / coller : un groupe neuf', { colles, gc })
await p.keyboard.press('Control+z'); await p.waitForTimeout(150)
// Ordre au clavier sur le groupe : Ctrl + Maj + ↓ (arrière-plan)
await O.vider(p); await O.clic(p, 275, 260); await p.waitForTimeout(150)
const zAvant = await p.evaluate(ids => ids.map(i => window.__app.forme(i).z), [T1, T2, Tri])
await p.keyboard.press('Control+Shift+ArrowDown'); await p.waitForTimeout(200)
const zApres = await p.evaluate(ids => ids.map(i => window.__app.forme(i).z), [T1, T2, Tri])
note('ordre Ctrl+Maj+↓ sur le groupe', { zAvant, zApres, msgs: (await O.msgs(p)).slice(-1) })
// Dégrouper : Ctrl + Maj + G ; puis Ctrl + Z regroupe d'un coup ; Ctrl + Z encore : défait le groupement d'un coup
await O.vider(p); await O.clic(p, 275, 260); await p.waitForTimeout(150)
await p.keyboard.press('Control+Shift+g'); await p.waitForTimeout(200)
ok((await groupes([T1, T2, Tri])).every(x => x === null), 'Ctrl + Maj + G dégroupe', { g: await groupes([T1, T2, Tri]), msgs: (await O.msgs(p)).slice(-1) })
await p.keyboard.press('Control+z'); await p.waitForTimeout(200)
const gz = await groupes([T1, T2, Tri])
ok(gz[0] && gz.every(x => x === gz[0]), 'Ctrl + Z rend le groupe d\'un coup', gz)
// Ctrl + G au clavier sur des objets libres, Ctrl+Z une fois
await O.vider(p)
const A = await O.poser(p, O.trait(200, 450, 100)), B = await O.poser(p, O.trait(200, 500, 100))
await choisir([A, B]); const pile0 = await O.pile(p)
await p.keyboard.press('Control+g'); await p.waitForTimeout(150)
ok(await O.pile(p) === pile0 + 1 && (await groupes([A, B]))[0], 'Ctrl + G : une étape d\'annulation', { pile0, pile: await O.pile(p) })
await p.keyboard.press('Control+z'); await p.waitForTimeout(150)
ok((await groupes([A, B])).every(x => x === null), 'Ctrl + Z défait le groupement d\'un coup', await groupes([A, B]))
await O.fin()
