// Point 7 : le contraste renforcé à l'écran (captures avec et sans), et le document inchangé.
import * as O from './lib/outils.mjs'
const { ok, note, C } = O
const ctx = await O.contexte()
const { p } = await O.ouvrir(ctx, 'contraste')
await p.evaluate(O.IMAGES); await p.evaluate(O.PAGE_NEUVE)
const I = await O.poser(p, O.image('vert', 100, 100, 240, 160))
const Tri = await O.poser(p, O.triangle(450, 100, { taille: 1 }))
const T = await O.poser(p, O.trait(150, 400, 200, { taille: 2 }))
await p.evaluate(ids => { const a = window.__app; a.selection.clear(); for (const i of ids) a.selection.add(i); a.rendu.redessinerDirect(); a.ui.maj() }, [I])
await p.waitForTimeout(300)
const json0 = await p.evaluate(() => JSON.stringify(window.__app.tableau.doc.toJSON()))
await p.screenshot({ path: C + '/captures/t11-normal.png' })
const bf = p.locator('button[aria-label^="Enregistrer, ouvrir"]')
await bf.click(); await p.waitForTimeout(200)
await p.locator('[data-action="contraste"]').click(); await p.waitForTimeout(400)
note('message', (await O.msgs(p)).slice(-1))
await p.evaluate(ids => { const a = window.__app; a.selection.clear(); for (const i of ids) a.selection.add(i); a.rendu.redessinerDirect(); a.ui.maj() }, [I])
await p.waitForTimeout(300)
await p.screenshot({ path: C + '/captures/t11-contraste.png' })
const json1 = await p.evaluate(() => JSON.stringify(window.__app.tableau.doc.toJSON()))
ok(json0 === json1, 'Le document ne change pas d\'un octet quand on coche le contraste', { a: json0.length, b: json1.length })
ok(await p.evaluate(() => localStorage.getItem('mem-contraste')) === '1', 'Le réglage est gardé sur l\'appareil (mem-contraste)')
await p.reload(); await p.waitForFunction(() => window.__app && window.__app.page); await p.waitForTimeout(500)
ok(await p.evaluate(() => document.body.classList.contains('contraste')), 'Après rechargement, toujours en contraste')
await O.fin()
