// Tour des menus du lot 5 à la souris, 1366 × 768 : relevé des entrées, des rôles aria, et captures.
import * as O from './lib/outils.mjs'
const { ok, note, C } = O
const ctx = await O.contexte()
const { p } = await O.ouvrir(ctx, 'souris')
await p.evaluate(O.IMAGES); await p.evaluate(O.PAGE_NEUVE)
const I = await O.poser(p, O.image('vert', 100, 100, 300, 200))
const T = await O.poser(p, O.trait(450, 150, 200))
const Tri = await O.poser(p, O.triangle(700, 100))
const F = await O.poser(p, O.formule(150, 400))
await p.waitForTimeout(300)
// 1. Menu complet de l'image et son ⋯
await O.clicDroit(p, 250, 200)
let e = await O.etat(p)
note('menu image', e)
await p.screenshot({ path: C + '/captures/t1-menu-image.png' })
await p.locator('.panneau-forme .ligne button.plus').click(); await p.waitForTimeout(150)
note('⋯ image', await p.evaluate(O.ENTREES, '.menu-plus'))
note('⋯ image aria', await p.evaluate(() => { const m = document.querySelector('.menu-plus'); return { role: m.getAttribute('role'), label: m.getAttribute('aria-label'), items: [...m.querySelectorAll('[role]')].map(x => [x.getAttribute('role'), x.getAttribute('aria-label'), x.getAttribute('aria-disabled'), x.getAttribute('aria-keyshortcuts')]) } }))
await p.screenshot({ path: C + '/captures/t1-plus-image.png' })
await p.keyboard.press('Escape'); await p.keyboard.press('Escape'); await O.vider(p)
// 2. formule
await O.clicDroit(p, 200, 420)
note('menu formule', await O.etat(p))
await p.locator('.panneau-forme .ligne button.plus').click(); await p.waitForTimeout(150)
note('⋯ formule', await p.evaluate(O.ENTREES, '.menu-plus'))
await p.keyboard.press('Escape'); await p.keyboard.press('Escape'); await O.vider(p)
// 3. trait
await O.clicDroit(p, 550, 150)
note('menu trait', await O.etat(p))
await p.locator('.panneau-forme .ligne button.plus').click(); await p.waitForTimeout(150)
note('⋯ trait', await p.evaluate(O.ENTREES, '.menu-plus'))
await p.keyboard.press('Escape'); await p.keyboard.press('Escape'); await O.vider(p)
// 4. triangle
await O.clicDroit(p, 750, 240)
note('menu triangle', await O.etat(p))
await p.locator('.panneau-forme .ligne button.plus').click(); await p.waitForTimeout(150)
note('⋯ triangle', await p.evaluate(O.ENTREES, '.menu-plus'))
await p.keyboard.press('Escape'); await p.keyboard.press('Escape'); await O.vider(p)
// 5. plusieurs
await p.keyboard.press('Control+a'); await p.waitForTimeout(200)
await O.clicDroit(p, 550, 150)
note('menu plusieurs', await O.etat(p))
await p.screenshot({ path: C + '/captures/t1-menu-plusieurs.png' })
await p.locator('.panneau-forme .ligne button.plus').click(); await p.waitForTimeout(150)
note('⋯ plusieurs', await p.evaluate(O.ENTREES, '.menu-plus'))
await p.keyboard.press('Escape'); await p.keyboard.press('Escape'); await O.vider(p)
// 6. menu de la page
await O.clicDroit(p, 600, 600)
note('menu page', await p.evaluate(O.ENTREES, '.menu-flottant[aria-label="Page"]'))
await p.keyboard.press('Escape')
// 7. menu gomme
await p.evaluate(() => window.__app.choisirOutil('gomme'))
await p.locator('.barre-outils button[data-outil="gomme"], .barre-outils button').filter({ hasText: '' }).first()
const gb = await p.evaluate(() => { const b = [...document.querySelectorAll('.barre-outils button')].find(b => /Gomme/.test(b.title)); const r = b.getBoundingClientRect(); return { x: r.x + r.width / 2, y: r.y + r.height / 2, title: b.title, aria: b.getAttribute('aria-label'), haspopup: b.getAttribute('aria-haspopup'), exp: b.getAttribute('aria-expanded') } })
note('bouton gomme', gb)
await p.mouse.click(gb.x, gb.y); await p.waitForTimeout(200)
note('menu gomme', await p.evaluate(O.ENTREES, '.menu-flottant[aria-label="Gomme"]'))
note('bouton gomme ouvert', await p.evaluate(() => { const b = [...document.querySelectorAll('.barre-outils button')].find(b => /Gomme/.test(b.title)); return { exp: b.getAttribute('aria-expanded'), focus: document.activeElement?.textContent } }))
await p.screenshot({ path: C + '/captures/t1-menu-gomme.png' })
await p.keyboard.press('Escape')
// 8. menu des fonds
await p.locator('.choix-fond').click(); await p.waitForTimeout(250)
note('menu fonds', await p.evaluate(() => { const m = document.querySelector('.menu-fonds'); return { role: m.getAttribute('role'), label: m.getAttribute('aria-label'), items: [...m.querySelectorAll('.fond-choix')].map(x => [x.getAttribute('role'), x.getAttribute('aria-checked'), x.textContent, x.getAttribute('aria-label'), x.title]), focus: document.activeElement?.textContent } }))
await p.screenshot({ path: C + '/captures/t1-menu-fonds.png' })
await p.keyboard.press('Escape')
// 9. menu ⋯ de la barre du haut
const bf = await p.evaluate(() => { const b = [...document.querySelectorAll('.barre-haut button, header button')].find(b => b.getAttribute('aria-haspopup') && /Enregistrer|Plus|Fichier/.test(b.title + b.getAttribute('aria-label'))); return b && { title: b.title, aria: b.getAttribute('aria-label') } })
note('bouton fichier', bf)
await O.fin()
