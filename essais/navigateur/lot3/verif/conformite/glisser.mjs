// Glisser-déposer à la souris (avec défilement au bord) et à la tablette graphique
import { ouvrir, preparer, etat, verifier, fin, pause, D, carte, plumeCDP } from './lib.mjs'

const { page, ctx } = await ouvrir({ viewport: { width: 1366, height: 600 } })
await preparer(page, 40, { ici: 0 })
await page.keyboard.press('Shift+P')
await pause(600)
let e = await etat(page)
const avant = e.cartes.slice()
// Souris : la page 1 tirée vers le bas de la grille, on attend que ça défile
const c0 = await carte(page, 0)
await page.mouse.move(c0.x, c0.y)
await page.mouse.down()
await page.mouse.move(c0.x + 3, c0.y + 3)
await page.mouse.move(c0.x + 10, c0.y + 10)
const bas = await page.evaluate(() => document.querySelector('.trieuse-grille').getBoundingClientRect().bottom)
await page.mouse.move(c0.x + 30, bas - 10, { steps: 6 })
await pause(1200)
e = await etat(page)
console.log('défilement pendant le glisser', e.defilement, 'fantôme', e.fantome)
await page.screenshot({ path: D + '/glisser.png' })
await page.mouse.move(c0.x + 30, bas - 120, { steps: 4 })
await pause(100)
await page.mouse.up()
await pause(200)
e = await etat(page)
const k = e.pages.indexOf(avant[0])
console.log('page 1 maintenant', k + 1, e.msgs.at(-1), e.toast)
verifier('Souris : la page tirée loin (défilement au bord) change de place', e.defilement > 0 && k > 10, { def: e.defilement, k })
// Annuler par le message
await page.locator('.toast button', { hasText: 'Annuler' }).click()
await pause(200)
e = await etat(page)
verifier('« Annuler » du message remet la page', e.pages.indexOf(avant[0]) === 0, e.msgs.at(-1))
// Stylet (Wacom) : tirer la carte 2 sur la carte 4
const cdp = await ctx.newCDPSession(page)
const plume = plumeCDP(cdp)
await page.evaluate(() => { document.querySelector('.trieuse-grille').scrollTop = 0 })
await pause(200)
const a = await carte(page, 1), b = await carte(page, 3, 0.8)
await plume('mouseMoved', a.x, a.y, false)
await plume('mousePressed', a.x, a.y, true)
for (let i = 1; i <= 10; i++) await plume('mouseMoved', a.x + (b.x - a.x) * i / 10, a.y + (b.y - a.y) * i / 10, true)
await pause(100)
await plume('mouseReleased', b.x, b.y, true)
await pause(200)
e = await etat(page)
console.log('Wacom', e.pages.indexOf(avant[1]) + 1, e.msgs.at(-1))
verifier('Tablette graphique : glisser sans appui long', e.pages.indexOf(avant[1]) === 3, e.msgs.at(-1))
await fin()
