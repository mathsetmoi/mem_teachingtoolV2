// La corbeille : poubelle, rechargement, vue, Remettre, Supprimer définitivement, Vider
import { ouvrir, preparer, etat, verifier, fin, pause, D } from './lib.mjs'

const { page } = await ouvrir()
const ids = await preparer(page, 5, { noms: { 1: 'Exercice 12 p. 84' }, ici: 1 })
await pause(300)
// Poubelle sur la page 2 (nommée), puis sur la page 4
const poubelle = () => page.locator('.barre-haut button[aria-label="Supprimer cette page"]').click()
await poubelle(); await pause(300)
let e = await etat(page)
console.log('après poubelle', e.msgs.at(-1), e.toast, e.pages.indexOf(e.page) + 1)
await page.evaluate(id => window.__app.allerPage(id), ids[3]); await pause(700)
await poubelle(); await pause(300)
e = await etat(page)
console.log('après 2e poubelle', e.msgs.at(-1), e.pages.length)
// Recharger
await page.reload()
await page.waitForFunction(() => window.__app && window.__app.page && document.querySelector('.rang')?.textContent?.includes('/'))
await pause(500)
await page.evaluate(() => { const a = window.__app, m = a.ui.message.bind(a.ui); window.__msgs = []; a.ui.message = (t, x, d) => { window.__msgs.push(t); return m(t, x, d) } })
e = await etat(page)
console.log('après rechargement', e.pages.length, 'corbeille', e.corbeille)
verifier('La corbeille survit au rechargement', e.corbeille.length === 2)
await page.keyboard.press('Shift+P'); await pause(500)
const btn = await page.evaluate(() => { const b = document.querySelector('.trieuse-bouton-corbeille'); return { txt: b.textContent, aria: b.getAttribute('aria-label') } })
console.log('bouton', btn)
await page.locator('.trieuse-bouton-corbeille').click(); await pause(800)
await page.screenshot({ path: D + '/corbeille.png' })
const vue = await page.evaluate(() => {
  const v = document.querySelector('.trieuse-corbeille')
  return { tete: v.querySelector('.corbeille-tete').innerText, note: v.querySelector('.corbeille-note')?.textContent,
    cartes: [...v.querySelectorAll('.carte-corbeille')].map(c => ({ aria: c.getAttribute('aria-label'), txt: c.innerText, canevas: !!c.querySelector('canvas') })),
    focus: document.activeElement?.getAttribute('aria-label') }
})
console.log(JSON.stringify(vue, null, 1))
// Remettre la page nommée (supprimée en premier : en second dans la liste)
await page.locator('.carte-corbeille', { hasText: 'Exercice' }).locator('.corbeille-remettre').click()
await pause(400)
e = await etat(page)
console.log('remise', e.msgs.at(-1), e.pages.indexOf(ids[1]) + 1, e.focus)
verifier('Remettre rend la page à sa place (2)', e.pages.indexOf(ids[1]) === 1)
// Supprimer définitivement l'autre
await page.locator('.trieuse-bouton-corbeille').click(); await pause(500)
await page.locator('.carte-corbeille .corbeille-supprimer').first().click(); await pause(300)
const q = await page.evaluate(() => { const d = document.querySelector('dialog[open]'); return d ? { txt: d.innerText, focus: document.activeElement?.textContent } : null })
console.log('question', q)
await page.screenshot({ path: D + '/question.png' })
await page.keyboard.press('Escape'); await pause(200)
e = await etat(page)
console.log('Échap sur la question', e.ouverte, e.dialog, await page.evaluate(() => !document.querySelector('.trieuse-corbeille').hidden))
await page.locator('.carte-corbeille .corbeille-supprimer').first().click(); await pause(300)
await page.locator('dialog[open] button', { hasText: 'Supprimer définitivement' }).click(); await pause(300)
e = await etat(page)
console.log('définitif', e.msgs.at(-1), e.corbeille)
const vide = await page.evaluate(() => document.querySelector('.trieuse-corbeille').innerText)
console.log('vue vide', vide)
await page.keyboard.press('Escape'); await pause(200)
e = await etat(page)
console.log('Échap → pages', e.ouverte, e.focus)
await fin()
