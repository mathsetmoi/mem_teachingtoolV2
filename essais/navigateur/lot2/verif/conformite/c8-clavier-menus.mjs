// Menus au clavier : le menu complet et le menu de la page ouverts au clic droit
import { contexte, charger, etat, boiteEcran, outil, poser, verifier, note, fin } from './lib.mjs'
const ctx = await contexte()
const { page } = await charger(ctx, 'clavier-menus')
const m = page.mouse
await outil(page, 'selection')
await page.evaluate(() => { const a = window.__app; a.cam.x = 0; a.cam.y = 0; a.cam.z = 1; a.rendu.toutRedessiner(); a.ui.maj() })
const T = await poser(page, { type: 'triangle', x: 500, y: 400 })
const b = await boiteEcran(page, T)
const x0 = await page.evaluate(id => JSON.stringify([window.__app.formes.find(f => f.id === id).x, window.__app.formes.find(f => f.id === id).y, window.__app.formes.find(f => f.id === id).pts?.slice(0,2)]), T)
await m.click(b.left + 1, (b.top + b.bottom) / 2, { button: 'right' })
await page.waitForTimeout(80)
let e = await etat(page)
note('menu complet', e.panneau, e.panneauLabel)
const focus0 = await page.evaluate(() => ({ tag: document.activeElement?.tagName, dansMenu: !!document.activeElement?.closest('.panneau-forme') }))
await page.keyboard.press('ArrowDown')
await page.waitForTimeout(100)
const x1 = await page.evaluate(id => JSON.stringify([window.__app.formes.find(f => f.id === id).x, window.__app.formes.find(f => f.id === id).y, window.__app.formes.find(f => f.id === id).pts?.slice(0,2)]), T)
const focus1 = await page.evaluate(() => ({ tag: document.activeElement?.tagName, txt: document.activeElement?.textContent?.slice(0, 20), dansMenu: !!document.activeElement?.closest('.panneau-forme') }))
note('menu complet, ↓', { focus0, focus1, y0: x0, y1: x1 })
verifier('menu complet ouvert au clic droit : ↓ ne déplace pas l\'objet (le focus va dans le menu)', x1 === x0 && focus1.dansMenu, { focus0, focus1, y0: x0, y1: x1 })
await page.keyboard.press('Tab')
const focus2 = await page.evaluate(() => ({ tag: document.activeElement?.tagName, txt: (document.activeElement?.getAttribute('aria-label') || document.activeElement?.textContent || '').slice(0, 30), dansMenu: !!document.activeElement?.closest('.panneau-forme') }))
note('Tab après ouverture', focus2)
await fin()
