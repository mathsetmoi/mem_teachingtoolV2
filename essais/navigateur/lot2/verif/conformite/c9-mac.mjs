// Mac : ⌘ dans les libellés, Ctrl + clic = clic droit, ⌘+C/V/D/A/Z
import { contexte, charger, etat, barre, boiteEcran, outil, poser, verifier, note, fin } from './lib.mjs'
const ctx = await contexte()
await ctx.addInitScript(() => { Object.defineProperty(Navigator.prototype, 'platform', { get: () => 'MacIntel' }) })
const { page } = await charger(ctx, 'mac')
const m = page.mouse
await outil(page, 'selection')
const T = await poser(page, { type: 'trait', x: 300, y: 300, l: 200 })
const b = await boiteEcran(page, T)
const cx = (b.left + b.right) / 2, cy = (b.top + b.bottom) / 2
await m.click(cx, cy)
const br = await barre(page)
note('titres', br?.boutons.map(x => x.titre))
verifier('Mac : la barre dit ⌘', br && br.boutons.find(x => x.libelle === 'Dupliquer').titre === 'Dupliquer (⌘ + D)', br?.boutons.map(x => x.titre))
const titres = await page.evaluate(() => [...document.querySelectorAll('button')].map(b => b.title).filter(t => /Annuler sur|Rétablir sur/.test(t)))
verifier('Mac : ↶ ↷ disent ⌘', titres.every(t => /⌘/.test(t)), titres)
await page.evaluate(() => { window.__app.selection.clear(); window.__app.ui.maj() })
await page.keyboard.down('Control'); await m.click(cx, cy); await page.keyboard.up('Control')
await page.waitForTimeout(80)
let e = await etat(page)
verifier('Mac : Ctrl + clic ouvre le menu complet', e.panneau && e.sel.includes(T), e)
await page.keyboard.press('Escape')
await m.click(cx, cy)
await page.keyboard.press('Meta+d')
await page.waitForTimeout(100)
e = await etat(page)
verifier('Mac : ⌘+D duplique', e.n === 2, e.n)
await page.keyboard.press('Meta+z')
e = await etat(page)
verifier('Mac : ⌘+Z annule', e.n === 1, e.n)
await page.keyboard.press('Meta+Shift+z')
e = await etat(page)
verifier('Mac : ⌘+Maj+Z rétablit', e.n === 2, e.n)
await m.click(1000, 600, { button: 'right' })
await page.waitForTimeout(80)
const tou = await page.evaluate(() => [...document.querySelectorAll('.menu-flottant[aria-label="Page"] .touche')].map(x => x.textContent))
verifier('Mac : menu de la page dit ⌘', tou.some(t => t === '⌘ + A'), tou)
await fin()
